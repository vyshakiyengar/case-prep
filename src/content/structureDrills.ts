// Structuring drills. Each prompt has one good first-level structure with its
// second level, where to start and the trap most candidates fall into.
// Pick questions offer four structures: one is good, the others each have one named flaw.

export type StructFamily = 'diagnose' | 'decide' | 'generate'
export interface StructPrompt {
  id: string
  family: StructFamily
  type: string
  framework?: string // core framework id
  prompt: string
  tree: { head: string; items: string[] }[]
  start: string
  trap: string
}

const P = (id: string, family: StructFamily, type: string, framework: string | undefined, prompt: string, tree: [string, string[]][], start: string, trap: string): StructPrompt =>
  ({ id, family, type, framework, prompt, tree: tree.map(([head, items]) => ({ head, items })), start, trap })

