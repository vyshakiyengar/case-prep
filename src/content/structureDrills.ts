// ---------- Spot the flaw: four first-level structures, one good
export type Flaw = 'good' | 'overlap' | 'gap' | 'generic' | 'not-the-question'
export const FLAW_LABEL: Record<Flaw, string> = {
  good: 'Good: MECE and specific',
  overlap: 'Overlap: two buckets cover the same thing',
  gap: 'Gap: a big driver is missing',
  generic: 'Generic: could be any case',
  'not-the-question': "Doesn't answer the question",
}
export interface StructPick {
  id: string
  prompt: string
  options: { buckets: string[]; flaw: Flaw; why: string }[]
}
const K = (id: string, prompt: string, options: [string[], Flaw, string][]): StructPick => ({ id, prompt, options: options.map(([buckets, flaw, why]) => ({ buckets, flaw, why })) })

